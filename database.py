
import os

import psycopg
from dotenv import load_dotenv
from psycopg.rows import tuple_row

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")


class HybridRow(tuple):
    """Support both row[0] and row['column_name'] access."""

    def __new__(cls, values, columns):
        obj = super().__new__(cls, values)
        obj.columns = columns
        return obj

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                key = self.columns.index(key)
            except ValueError:
                raise KeyError(key) from None
        return super().__getitem__(key)



def hybrid_row_factory(cursor):
    if cursor.description is None:
        return tuple_row

    columns = [column.name for column in cursor.description]

    def make_row(values):
        return HybridRow(values, columns)

    return make_row


def get_connection():
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Check the project .env file."
        )

    return psycopg.connect(
        DATABASE_URL,
        row_factory=hybrid_row_factory,
        connect_timeout=10,
    )


def _get_columns(connection, table_name):
    cursor = connection.cursor()
    cursor.execute(
        """
        SELECT column_name
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = %s
        """,
        (table_name,),
    )
    return {row[0] for row in cursor.fetchall()}


def create_table():
    connection = get_connection()
    try:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                transaction_id TEXT,
                date TEXT NOT NULL,
                type TEXT NOT NULL,
                category TEXT NOT NULL,
                sub_category TEXT NOT NULL,
                amount DOUBLE PRECISION NOT NULL,
                description TEXT,
                is_deleted INTEGER DEFAULT 0,
                user_id INTEGER REFERENCES users(id)
            )
        """)
        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_transactions_user_id
            ON transactions(user_id)
        """)
        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_transactions_user_date
            ON transactions(user_id, date)
        """)
        connection.commit()
    finally:
        connection.close()


def add_deleted_column():
    connection = get_connection()
    try:
        columns = _get_columns(connection, "transactions")
        if "is_deleted" not in columns:
            connection.execute("""
                ALTER TABLE transactions
                ADD COLUMN is_deleted INTEGER DEFAULT 0
            """)
        connection.commit()
    finally:
        connection.close()


